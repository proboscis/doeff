"""Failure cases for the .pyi files, among the type declarations of this doeff-core-effects Hy modules, that doeff_hy._static_stub generated (#2842).

The 13 modules of this package's .hy that imports from the users' repo main and had no .pyi: when a user added a line that uses those names,
the strict type gate stopped with an Unknown red that the writer could not fix (in descending order of users: os_process, aiohttp_http_server,
scheduler_channel, scripted_freeze). The .pyi is generated by the tool from the .hy (modules with a hand-written .pyi are not checked here).
The remaining 4 public modules (offloaded_call, pooled_postgres_sql, python_bytecode, sql_transaction) made the import line "unresolvable" in both
pyright and mypy (gap 8 in the pre-publication type report, 2026-10-17).

- In a probe module that binds, one by one, the names users import, no "type is unknown" red appears (removing the .pyi makes it red).
- Every public .hy (name not starting with _) has a tool-generated .pyi next to it (inward-facing ones such as _memo_handlers_impl are excluded).
- The .pyi are not committed: the build hook makes them from the .hy at every install (`uv sync`, the wheel build — tools/doeff_hy_stub_hook.py).
"""

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from doeff_hy._static_stub import generated

# The stub (.pyi) is written with the type-parameter syntax (PEP 695 -- `class SqlTransaction[T]`), which the 3.11 ast cannot read. Matching the stub against the module
# does not depend on the Python version, so it is viewed from 3.12.
pytestmark = pytest.mark.skipif(sys.version_info < (3, 12), reason="the stub's type-parameter syntax needs Python 3.12 or later")

SOURCE = Path(__file__).resolve().parents[1]

needs_pyright = pytest.mark.skipif(shutil.which("pyright") is None, reason="pyright is not available")

# Names that the users' repo main imports (per module; counted 2026-10-02). The modules are named by their _ path: the
# relocation modules at the old paths were deleted (ADR-DOE-API-001 R5, stage 3), and the users read the names from the entry.
USED = {
    "_aiohttp_http_server": ("aiohttp-http-server",),
    "_clickhouse_http_sql": ("ClickHouseDatabase", "clickhouse-http-sql-handler", "clickhouse-schema-statements"),
    "_gc_freeze": ("gc-freeze-handler",),
    "_heap_effects": ("CollectAndFreeze",),
    "_inline_compute": ("inline-compute-handler",),
    "_os_process": ("subprocess-handler",),
    "_os_random": ("os-random-handler",),
    "_postgres_sql": ("PostgresConnections", "PostgresDatabase", "postgres-sql-handler"),
    "_process_latest": ("process-latest-handler",),
    "_process_meter": ("process-meter-handler",),
    "_scheduler_channel": ("scheduler-channel-handler",),
    "_scripted_freeze": ("scripted-freeze-handler",),
    "_thread_pool_compute": ("thread-pool-compute-handler",),
}

# Among the names of the 4 public modules that had no .pyi, the names that this package's modules and probes import (counted 2026-10-17).
USED_IN_PACKAGE = {
    "_offloaded_call": ("ThreadPerCall", "offloaded", "run-detached", "keep-nothing"),
    "_pooled_postgres_sql": ("pooled-postgres-sql-handler",),
    "_python_bytecode": (
        "checked-hash-pyc",
        "compiled-pyc",
        "kept-pyc",
        "pyc-path",
        "compile-python-sources",
        "prepare-compile-path",
    ),
    "_sql_transaction": ("TransactionFlush", "run-in-transaction", "run-in-batched-transaction", "stray-batch"),
}

PROBED = {**USED, **USED_IN_PACKAGE}


def _probe() -> str:
    """Probe module that binds names one by one to other names (if the bound name's type is Unknown, a strict red appears on that line)."""
    imports = [f"(import doeff_core_effects.{module} [{' '.join(names)}])" for module, names in PROBED.items()]
    bindings = [
        f"(setv used-{index} {name})" for index, name in enumerate(name for names in PROBED.values() for name in names)
    ]
    return "\n".join([*imports, "", *bindings, ""])


def _errors(root: Path) -> list[str]:
    """The red text from checking the probe module with the same strict as the users' type gate."""
    done = subprocess.run(
        [sys.executable, "-m", "doeff_hy._static_check", "--root", str(root), "--json", "--strict", "--no-cache", str(root / "probe.hy")],
        capture_output=True,
        text=True,
        timeout=240,
        check=False,
    )
    diagnostics = json.loads(done.stdout) if done.stdout.strip() else []
    return [f"{d['line']}: {d['rule']}: {d['message']}" for d in diagnostics if d["severity"] == "error"]


@needs_pyright
def test_names_the_users_import_are_not_unknown(tmp_path: Path) -> None:
    (tmp_path / "probe.hy").write_text(_probe(), encoding="utf-8")
    errors = _errors(tmp_path)
    assert not [e for e in errors if "hy-compile" in e], errors
    assert not [e for e in errors if re.search(r"is unknown|could not be resolved|unknown import symbol", e)], errors


def test_every_public_hy_module_has_a_generated_stub() -> None:
    # Without a .pyi, the import line cannot be resolved in the users' type check. The build makes the .pyi of every .hy (tools/doeff_hy_stub_hook.py).
    package = SOURCE / "doeff_core_effects"
    stubless = [
        source.name
        for source in sorted(package.glob("*.hy"))
        if not source.name.startswith("_") and not generated(source.with_suffix(".pyi"))
    ]
    assert stubless == []
