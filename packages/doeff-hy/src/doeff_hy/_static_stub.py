"""Build the type declarations (.pyi) of a Hy module from the expansion used for type checking.

The expansion used for type checking (static_check.project) returns a module tree in which the defk / deff contracts (`(: x T)` in :pre, `(: % T)` in :post) and
the `#^` of defrecord fields are turned into Python annotations. This module strips the bodies from that tree and keeps only the public-surface declarations
— the macro semantics stay defined in one place, the expansion (no second reader is created just for .pyi).

Declaration shapes:
- defk (a `@_doeff_do` function) -> `def name(args) -> _Program[answer, object]: ...`. answer = the :post type (a :post that is not a type becomes
  Incomplete). The effect position is object (Program is covariant in both answer and effect — same as the hand-written .pyi in doeff-records and doeff-cluster).
- defhandler (a function that returns a function wrapping an answerer) -> `def name(args) -> _Handler: ...` (doeff_hy._static_types.Handler).
- ordinary functions (deff, defn) -> keep the annotations and make the body `...`. Parameters and answers without annotations are Incomplete.
- class -> keep decorators, bases, field annotations, and method shapes. Defaults of fields and parameters are kept if literal, `...` if expressions. The `:tp [T]` of defeffect
  is carried as the class type parameter (`class E[T](…)`), and the answer type of the base reads T (#2939).
- constants -> the annotation if present; a literal, a tuple/dict of literals gives its type; type unions (`A | B`) and TypeVar are kept as written. Values whose type
  cannot be produced become Incomplete (typeshed's "type not yet available" marker), and the name is recorded in StubText.incomplete.
- import -> re-exported in the form `from m import X as X` (a runtime module holds the imported names as attributes and users look them up —
  e.g. MaintenancePlan in doeff_records._main). Macro helpers (`_doeff_*`, doeff_hy._static_types) and `hy` are dropped.

The .pyi are not committed: each package's build (tools/doeff_hy_stub_hook.py, the hatch build hook of `uv sync` and of the wheel build) makes them with
build_stubs (CLI --build), so a .hy change cannot reach main with a stale .pyi (committed .pyi lagged their .hy more than 10 times).
build_stubs reads the expansion cache (static_cache), whose record already names what an expansion depended on (the .hy, the macros it used and the
modules they read, the post-processing), so only the .hy whose expansion changed are expanded again; the declarations are rendered from every expansion
each time, so a change of this file reaches every .pyi. A hand-written .pyi (one without MARK_HEAD at the top) is never overwritten unless --replace is given.
"""

