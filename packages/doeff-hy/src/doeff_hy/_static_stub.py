MARK_HEAD = "# doeff_hy._static_stub "

#: Built-in names read as types when they are leaves of a type union (`A | B`) (CamelCase names are read as types because they are classes).
_BUILTIN_TYPES = frozenset(
    {"dict", "list", "tuple", "set", "frozenset", "str", "int", "float", "bool", "bytes", "bytearray", "complex", "object", "type"}
)
#: Type constructors kept in a declaration in their value form (for TypeVar and similar, the assignment form itself is the type declaration).
_TYPE_MAKERS = frozenset({"TypeVar", "ParamSpec", "TypeVarTuple", "NewType"})
#: Method decorators kept in a declaration (only those that carry type meaning).
_METHOD_DECORATORS = frozenset({"staticmethod", "classmethod", "property", "overload", "abstractmethod"})
#: Names of the decorator that wraps a defk (`_doeff_do` in the type-checking expansion, and `do` as written by users).
_DO_DECORATORS = frozenset({"_doeff_do", "do"})
#: Module-level names that are not exposed on the type surface (module markers, Hy gensyms, macro bookkeeping).
_HIDDEN_NAMES = frozenset({"MODULE_TAGS"})
_HIDDEN_PREFIXES = (GENERATED_NAME_PREFIX, "__doeff_", "_doeff_")
#: str methods that return str (to read the type when a constant's value is built like `X.format(...)`).
_STR_METHODS = frozenset({"format", "join", "strip", "lower", "upper", "replace", "removeprefix", "removesuffix"})
#: Special methods that always return None (read as None even without an annotation).
_NONE_METHODS = frozenset({"__init__", "__post_init__"})
#: Name of the marker for places where no type could be produced (typeshed's _typeshed.Incomplete).
_INCOMPLETE = "Incomplete"
#: os.path functions that return str (to read the type of path constants built from the module's location).
_PATH_FUNCTIONS = frozenset({"dirname", "abspath", "basename", "join", "realpath", "normpath", "expanduser"})


@dataclass(frozen=True)
class StubText:
    """Body of the .pyi built from one .hy, plus the names where no type could be produced and Incomplete was used (a list of places where the author should add contracts)."""

    text: str
    incomplete: tuple[str, ...]


class StubUnmade(Exception):
    """.hy could not be read by the type-checking expansion, so no .pyi was generated (a Hy compile error)."""


@dataclass(frozen=True)
class _Declared:
    """One module-level declaration (kept paired with its name so that, if the same name is declared again later, the later one wins)."""

    name: str
    node: ast.stmt


@dataclass(frozen=True)
class _Helper:
    """One helper type import placed at the top of the .pyi only when a declaration reads it (Program, Handler, Incomplete, TypeAlias, defeffect helpers)."""

    reads: str
    module: str
    name: str
    asname: str | None


#: Helper type imports (placed only when a declaration reads the name). The last two are macro helper names imported by the defeffect expansion and
#: read as-is by the declaration's bases and decorators — imports of hidden names (_doeff_) are not re-exported, so without placing them here the .pyi would keep names
#: with no definition, and users saw the effect base as Unknown (and the answer type as Unknown too).
_HELPERS = (
    _Helper("TypeAlias", "typing", "TypeAlias", None),
    _Helper("Incomplete", "_typeshed", "Incomplete", None),
    _Helper("_Program", "doeff", "Program", "_Program"),
    _Helper("_Handler", "doeff_hy._static_types", "Handler", "_Handler"),
    _Helper("_Never", "typing", "Never", "_Never"),
    _Helper("_doeff_effect_base", "doeff", "EffectBase", "_doeff_effect_base"),
    _Helper("_doeff_dataclass", "dataclasses", "dataclass", "_doeff_dataclass"),
    _Helper("_doeff_BoundRun", "doeff_hy._static_types", "BoundRun", "_doeff_BoundRun"),
)
#: Names that a helper import may place at the top of the .pyi (even hidden names may remain in a declaration).
_HELPER_NAMES = frozenset(helper.asname or helper.name for helper in _HELPERS)


@dataclass(frozen=True)
class _Scan:
    """State partway through reading the module top level from the top — carried in reading order so later constants can look up the types of earlier ones."""

    imports: tuple[ast.stmt, ...]
    declarations: tuple[_Declared, ...]
    #: Declarations of module-level functions (including names not exposed on the type surface — so the type of `x = _hy_anon_3()` can be derived from that function's answer).
    functions: tuple[_Declared, ...] = ()

    def declared(self, name: str, node: ast.stmt) -> "_Scan":
        """Return the next state with one more declaration added."""
        return replace(self, declarations=(*self.declarations, _Declared(name, node)))

    def defined(self, name: str, node: ast.FunctionDef, public: bool) -> "_Scan":
        """Return the next state after remembering one function (also added to the declarations if the name is public)."""
        known = replace(self, functions=(*self.functions, _Declared(name, node)))
        return known.declared(name, node) if public else known

    def effect_free(self, name: str) -> "_Scan":
        """Return the next state in which, for a defk declared with `:effects []` (emits no effects), the effect position of the answer Program is set to Never
        (the claim the hand-written .pyi made as `Program[X, Never]`, now carried by the tool; #2939). Unchanged if there is no function of that name or its answer is not a Program."""

        def freed(item: _Declared) -> _Declared:
            node = item.node
            match node:
                case ast.FunctionDef(name=found, returns=ast.Subscript(value=ast.Name(id="_Program"), slice=ast.Tuple(elts=[answer, _]))) if found == name:
                    return _Declared(item.name, _with_returns(node, _subscript("_Program", answer, _name("_Never"))))
                case _:
                    return item

        return replace(
            self,
            declarations=tuple(freed(item) for item in self.declarations),
            functions=tuple(freed(item) for item in self.functions),
        )

    def answer_of(self, name: str) -> ast.expr | None:
        """Type of the value from calling a function of a module read earlier (the function declaration's answer — e.g. `x = _hy_anon_3()` of a defhandler with no arguments)."""
        answers = [d.node.returns for d in self.functions if d.name == name and isinstance(d.node, ast.FunctionDef)]
        return answers[-1] if answers and answers[-1] is not None else None

    def kind_of(self, name: str) -> ast.expr | None:
        """Type of a constant read earlier (the type of an annotation-only declaration with no value — looked up when a later constant's value reads that name)."""
        kinds = [
            d.node.annotation
            for d in self.declarations
            if d.name == name and isinstance(d.node, ast.AnnAssign) and d.node.value is None
        ]
        return kinds[-1] if kinds else None

    def type_vars(self) -> frozenset[str]:
        """Names of type parameters read earlier (such as `T = TypeVar("T")` — so that a later class's answer type reads that name as a type; #2925)."""
        return frozenset(
            d.name
            for d in self.declarations
            if isinstance(d.node, ast.Assign)
            and isinstance(d.node.value, ast.Call)
            and isinstance(d.node.value.func, ast.Name | ast.Attribute)
            and (d.node.value.func.id if isinstance(d.node.value.func, ast.Name) else d.node.value.func.attr) in _TYPE_MAKERS
        )


def _type_params(node: ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef) -> "list[ast.type_param]":
    """To carry the type parameters of a definition (`def f[T]`, `class C[T]` — from contracts and the :tp of defeffect) into the declaration. The ast definition has type parameters only
    from Python 3.12 — a 3.11 definition has none (the :tp type-check expansion is also 3.12 and later), so it is read the same as a definition without type parameters."""
    if sys.version_info >= (3, 12):
        return list(node.type_params)
    return []


def _with_returns(node: ast.FunctionDef, returns: ast.expr) -> ast.FunctionDef:
    """Return a declaration with only the answer type of a function declaration replaced (other fields unchanged)."""
    return ast.FunctionDef(
        name=node.name,
        args=node.args,
        body=node.body,
        decorator_list=node.decorator_list,
        returns=returns,
        type_params=_type_params(node),
    )


def _absolute(path: Path) -> Path:
    """Normalize to an absolute path without following symlinks, for comparing roots and displaying relative paths."""
    return Path(os.path.normpath(path.absolute()))


def hidden_name(name: str) -> bool:
    """Whether this is a name not exposed on the type surface (module markers, Hy gensyms, macro helpers and bookkeeping). The check that compares hand-written declarations with the implementation
    (test_hy_module_stubs in doeff-core-effects) also decides public names in this one place (the tool hid MODULE_TAGS
    while the check counted them, a mismatch that turned a module with a tag added at the top red)."""
    return name in _HIDDEN_NAMES or name.startswith(_HIDDEN_PREFIXES)


def _camel(name: str) -> bool:
    """Whether this is a CamelCase name readable as a class name (to separate it from all-caps constant names; a leading `_` is stripped as the mark of a module-internal class)."""
    bare = name.lstrip("_")
    return bare[:1].isupper() and any(c.islower() for c in bare)


def _name(text: str) -> ast.Name:
    """Build the expression for a name placed in a declaration (reading context)."""
    return ast.Name(id=text, ctx=ast.Load())


def _subscript(base: str, *items: ast.expr) -> ast.Subscript:
    """Build the type expression `base[items]` (element types of a container, the answer type of a Program)."""
    index: ast.expr = items[0] if len(items) == 1 else ast.Tuple(elts=list(items), ctx=ast.Load())
    return ast.Subscript(value=_name(base), slice=index, ctx=ast.Load())


def _union(types: list[ast.expr]) -> ast.expr:
    """Combine element types into one type union (identical types collapse to one, in order of appearance)."""
    keys = [ast.unparse(item) for item in types]
    unique = [item for index, item in enumerate(types) if keys[index] not in keys[:index]]
    return reduce(lambda folded, item: ast.BinOp(left=folded, op=ast.BitOr(), right=item), unique[1:], unique[0])


def _type_like(node: ast.expr) -> bool:
    """Whether the value is a type expression (type unions and type subscripts are kept as type aliases)."""
    match node:
        case ast.Constant(value=None):
            return True
        case ast.Name(id=name):
            return name in _BUILTIN_TYPES or _camel(name)
        case ast.Attribute(attr=attr):
            return _camel(attr)
        case ast.Subscript(value=base):
            return _type_like(base)
        case ast.BinOp(op=ast.BitOr()):
            # If all leaves of the union have type-expression form and at least one is None or a built-in type, it is a type union (None or int never mixes into a `|` of values —
            # so a union that includes the lowercase class `datetime` is also read as a type).
            leaves = _union_leaves(node)
            shaped = all(isinstance(leaf, ast.Name | ast.Attribute | ast.Subscript) or _none(leaf) for leaf in leaves)
            return shaped and any(_type_like(leaf) for leaf in leaves)
        case _:
            return False


def _annotation(node: ast.expr | None) -> ast.expr | None:
    """Turn an expansion annotation (contract types arrive as string annotations `'T'`) into the type expression written in the .pyi."""
    match node:
        case ast.Constant(value=str(text)):
            try:
                return ast.parse(text, mode="eval").body
            except SyntaxError:
                return node
        case _:
            return node


def _default(node: ast.expr) -> ast.expr:
    """Convert a default value to .pyi form: keep literals (including negative numbers) and make expressions `...` (do not copy expressions into a declaration with no body)."""
    match node:
        case ast.Constant():
            return node
        case ast.UnaryOp(op=ast.USub(), operand=ast.Constant()):
            return node
        case _:
            return ast.Constant(value=...)


def _elements(items: list[ast.expr], scan: _Scan) -> list[ast.expr] | None:
    """Sequence of element types of a container (None if even one cannot be produced — do not emit a half-formed container type)."""
    found = [_value_type(item, scan) for item in items]
    return [kind for kind in found if kind is not None] if all(kind is not None for kind in found) else None


def _container(maker: str, items: list[ast.expr], scan: _Scan) -> ast.expr | None:
    """Type of a literal container (a tuple is the variable-length `tuple[T, ...]`)."""
    kinds = _elements(items, scan)
    if not kinds:
        return None
    return _subscript("tuple", _union(kinds), ast.Constant(value=...)) if maker == "tuple" else _subscript(maker, _union(kinds))


def _value_type(node: ast.expr, scan: _Scan) -> ast.expr | None:
    """Read the type of a constant's value from its literal form (None if unreadable — the caller makes it Incomplete)."""
    match node:
        case ast.Constant(value=bool()):
            return _name("bool")
        case ast.Constant(value=None):
            return ast.Constant(value=None)
        case ast.Constant(value=int()):
            return _name("int")
        case ast.Constant(value=float()):
            return _name("float")
        case ast.Constant(value=str()) | ast.JoinedStr():
            return _name("str")
        case ast.Constant(value=bytes()):
            return _name("bytes")
        case ast.UnaryOp(op=ast.USub() | ast.UAdd(), operand=ast.Constant(value=int() | float()) as operand) if not isinstance(
            operand.value, bool
        ):
            # Signed numeric literal (`(val STOPPED-CODE -15)` expands to `-15` = a unary operation — the numeric type is the same with a sign; #2887)
            return _value_type(operand, scan)
        case ast.Name(id=name) if (kind := scan.kind_of(name)) is not None:
            return kind
        case ast.Name(id=name) if _camel(name):
            # The class name itself (an element of a container — a table of effect types such as `(val SIM-PASSABLE #(Spawn Wait …))`) is a class value, so type
            # (previously unreadable and Incomplete — the tool could not produce the hand-written .pyi's tuple[type, ...]; continuation of the doeff red in agora-redesign).
            return _name("type")
        case ast.Tuple(elts=[]):
            return _subscript("tuple", ast.Tuple(elts=[], ctx=ast.Load()))
        case ast.Tuple(elts=items):
            return _container("tuple", items, scan)
        case ast.List(elts=items) if items:
            return _container("list", items, scan)
        case ast.Set(elts=items):
            return _container("set", items, scan)
        case ast.Call(func=ast.Name(id=("tuple" | "list" | "set" | "frozenset") as maker), args=[ast.Tuple(elts=items) | ast.List(elts=items)]) if items:
            return _container(maker, items, scan)
        case ast.Call(func=ast.Name(id=("tuple" | "list" | "set" | "frozenset") as maker), args=[ast.GeneratorExp(elt=item) | ast.ListComp(elt=item)]):
            return _container(maker, [item], scan)
        case ast.ListComp(elt=item):
            return _container("list", [item], scan)
        case ast.Dict(keys=keys, values=values) if keys and all(key is not None for key in keys):
            key_kinds = _elements([key for key in keys if key is not None], scan)
            value_kinds = _elements(values, scan)
            return _subscript("dict", _union(key_kinds), _union(value_kinds)) if key_kinds and value_kinds else None
        case ast.BinOp(left=left, op=ast.Add(), right=right):
            return _sum_type(_value_type(left, scan), _value_type(right, scan))
        case ast.BinOp(left=left, op=ast.Sub() | ast.Mult() | ast.FloorDiv() | ast.Mod() | ast.Pow(), right=right):
            return _number_type(_value_type(left, scan), _value_type(right, scan))
        case ast.Call(func=ast.Name(id=("str" | "int" | "float" | "bool" | "bytes") as maker)):
            return _name(maker)
        case ast.Call(func=ast.Attribute(value=base, attr=method)) if method in _STR_METHODS:
            kind = _value_type(base, scan)
            return kind if kind is not None and ast.unparse(kind) == "str" else None
        case ast.Call(func=ast.Attribute(value=ast.Attribute(value=ast.Name(id="os"), attr="path"), attr=function)) if function in _PATH_FUNCTIONS:
            return _name("str")
        case ast.Attribute(value=ast.Name(id=owner), attr=member) if _camel(owner) and member.isupper():
            return _name(owner)
        case ast.Call(func=ast.Name(id=function)) if (answer := scan.answer_of(function)) is not None:
            return answer
        case ast.Call(func=ast.Name(id=maker)) if _camel(maker):
            return _name(maker)
        case _:
            return None


def _sum_type(left: ast.expr | None, right: ast.expr | None) -> ast.expr | None:
    """Type of `a + b` (same types, and variable-length tuples, give a tuple of the union of element types. Others are not read)."""
    if left is None or right is None:
        return None
    match left, right:
        case (
            ast.Subscript(value=ast.Name(id="tuple"), slice=ast.Tuple(elts=[first, ast.Constant(value=builtins.Ellipsis)])),
            ast.Subscript(value=ast.Name(id="tuple"), slice=ast.Tuple(elts=[second, ast.Constant(value=builtins.Ellipsis)])),
        ):
            return _subscript("tuple", _union([first, second]), ast.Constant(value=...))
        case _ if ast.unparse(left) == ast.unparse(right) and ast.unparse(left) in ("str", "bytes", "int", "float"):
            return left
        case _:
            return None


def _number_type(left: ast.expr | None, right: ast.expr | None) -> ast.expr | None:
    """Type of arithmetic between numbers (size constants such as `(* 32 1024 1024)`): int with int is int; if a float is mixed in, float."""
    kinds = {ast.unparse(k) for k in (left, right) if k is not None}
    if left is None or right is None or not kinds <= {"int", "float"}:
        return None
    return _name("float" if "float" in kinds else "int")


def _union_leaves(node: ast.expr) -> list[ast.expr]:
    """Sequence of leaves of `A | B | C` (to check leaf by leaf whether it is a type union)."""
    match node:
        case ast.BinOp(left=left, op=ast.BitOr(), right=right):
            return [*_union_leaves(left), *_union_leaves(right)]
        case _:
            return [node]


def _none(node: ast.expr) -> bool:
    """Whether this is a None literal (a None leaf of a type union)."""
    return isinstance(node, ast.Constant) and node.value is None


def _keeps(decorator: ast.expr) -> bool:
    """Whether a function decorator carries type meaning and so stays in the .pyi (including `x.setter`)."""
    match decorator:
        case ast.Name(id=name):
            return name in _METHOD_DECORATORS
        case ast.Attribute(attr=("setter" | "getter" | "deleter")):
            return True
        case _:
            return False


def _reads_hidden(node: ast.expr) -> bool:
    """Whether the expression reads a macro helper name that cannot be placed at the top of the .pyi (so that no unresolvable name is left when copying to the .pyi — names a helper import
    can place are resolvable, so they are not counted: the defeffect `@_doeff_dataclass(frozen=True)` is kept)."""
    return any(isinstance(n, ast.Name) and hidden_name(n.id) and n.id not in _HELPER_NAMES for n in ast.walk(node))


def _class_var(annotation: ast.expr) -> bool:
    """Whether a field annotation is ClassVar (a class value is not a dataclass field, so the default is not copied)."""
    match annotation:
        case ast.Name(id="ClassVar") | ast.Subscript(value=ast.Name(id="ClassVar")):
            return True
        case _:
            return False


def _arguments(arguments: ast.arguments, method: bool) -> ast.arguments:
    """Turn the parameter list into .pyi form (annotations become type expressions; unannotated parameters become Incomplete; defaults are literals or `...`)."""
    positional = [*arguments.posonlyargs, *arguments.args]
    receiver = positional[0].arg if method and positional and positional[0].arg in ("self", "cls") else None

    def typed(arg: ast.arg) -> ast.arg:
        """Attach a type to one parameter (a method's self / cls are left unannotated)."""
        annotation = _annotation(arg.annotation)
        if annotation is None and arg.arg != receiver:
            annotation = _name(_INCOMPLETE)
        return ast.arg(arg=arg.arg, annotation=annotation)

    return ast.arguments(
        posonlyargs=[typed(a) for a in arguments.posonlyargs],
        args=[typed(a) for a in arguments.args],
        vararg=None if arguments.vararg is None else typed(arguments.vararg),
        kwonlyargs=[typed(a) for a in arguments.kwonlyargs],
        kw_defaults=[None if d is None else _default(d) for d in arguments.kw_defaults],
        kwarg=None if arguments.kwarg is None else typed(arguments.kwarg),
        defaults=[_default(d) for d in arguments.defaults],
    )


def _returns(node: ast.FunctionDef | ast.AsyncFunctionDef) -> ast.expr:
    """Answer type of a function: defk wraps it in Program, defhandler is Handler, others keep the annotation (Incomplete if none)."""
    if any(isinstance(d, ast.Name) and d.id in _DO_DECORATORS for d in node.decorator_list):
        return _subscript("_Program", _annotation(node.returns) or _name(_INCOMPLETE), _name("object"))
    if any(isinstance(s, ast.FunctionDef) and s.name == "__doeff_handler_fn__" for s in node.body):
        return _name("_Handler")
    declared = _annotation(node.returns)
    if declared is not None:
        return declared
    return ast.Constant(value=None) if node.name in _NONE_METHODS else _name(_INCOMPLETE)


def _function(node: ast.FunctionDef | ast.AsyncFunctionDef, method: bool) -> ast.FunctionDef:
    """Declaration of one function (body is `...`; decorators without type meaning are dropped)."""
    return ast.FunctionDef(
        name=node.name,
        args=_arguments(node.args, method),
        body=[ast.Expr(value=ast.Constant(value=...))],
        decorator_list=[d for d in node.decorator_list if _keeps(d)],
        returns=_returns(node),
        # The contract's :tp (type parameters) becomes `def f[T]` in the type-check expansion — carry into the .pyi the generics of functions whose answer is determined by the argument type (#2893).
        type_params=_type_params(node),
    )


def _member(statement: ast.stmt) -> ast.stmt | None:
    """Declaration of one statement in a class body (field, class value, method, nested class; None for a statement with no type surface). Names of macro bookkeeping
    (hidden names such as defeffect's `__doeff_answer__` and defwire's `__doeff_wire__`) are not copied — the base holds the answer type, and copying it as a field
    was also counted as a field by the hand-written .pyi field comparison (the order of dataclass fields; #2886)."""
    match statement:
        case ast.AnnAssign(target=ast.Name() as target, annotation=annotation, value=value) if not hidden_name(target.id):
            kind = _annotation(annotation) or annotation
            kept = None if value is None or _class_var(kind) else _default(value)
            return ast.AnnAssign(target=target, annotation=kind, value=kept, simple=1)
        case ast.Assign(targets=[ast.Name() as target], value=value) if not hidden_name(target.id):
            return ast.Assign(targets=[target], value=_default(value))
        case ast.FunctionDef() | ast.AsyncFunctionDef() if not hidden_name(statement.name):
            return _function(statement, method=True)
        case ast.ClassDef():
            return _class(statement)
        case _:
            return None


def _declared_answer(statement: ast.stmt, type_vars: frozenset[str]) -> ast.expr | None:
    """If a defeffect class body statement is the place for the answer type (`__doeff_answer__ = _doeff_cast(object, (A, B, …))`), the union of its elements.
    None if the elements are not type expressions (runtime values such as `(type None)`). Module type-parameter names (type_vars) are read as types
    (`:answer (| T SqlFailed SqlUnreachable)` — the name is one capital letter and does not match the class-name shape test; #2925)."""
    match statement:
        case ast.AnnAssign(
            target=ast.Name(id="__doeff_answer__"),
            value=ast.Call(func=ast.Name(id="_doeff_cast"), args=[_, ast.Tuple(elts=[_, *_] as elements)]),
        ) if all(_type_like(element) or (isinstance(element, ast.Name) and element.id in type_vars) for element in elements):
            return _union(elements)
        case _:
            return None


def _effect_base(base: ast.expr, answer: ast.expr | None) -> ast.expr:
    """To put the answer type on the defeffect base (a bare EffectBase) — so the user's `<-` (in the type-check expansion `_doeff_perform(e)` = the T of e's
    Program[T]) can read the answer (left bare, the user would see the answer as Unknown). The type-check expansion's
    defeffect base stays bare (so the defining module's check does not gain a red for a bare generic answer; #2322), and only the .pyi carries the answer."""
    match base:
        case ast.Name(id="_doeff_effect_base") if answer is not None:
            return _subscript("_doeff_effect_base", answer)
        case _:
            return base


def _given_default(annotated: ast.stmt, following: ast.stmt | None) -> ast.AnnAssign | None:
    """If the statement right after an annotation-only statement (`#^ float timeout`) is an assignment to the same name (`(setv timeout 30.0)`), combine the two into one statement `name: type = value`."""
    match annotated, following:
        case (
            ast.AnnAssign(target=ast.Name(id=name) as target, annotation=annotation, value=None),
            ast.Assign(targets=[ast.Name(id=assigned)], value=value),
        ) if assigned == name:
            return ast.AnnAssign(target=target, annotation=annotation, value=value, simple=1)
        case _:
            return None


def _member_name(member: ast.stmt) -> str | None:
    """Names bound by one class-body declaration (so fields of __init__ are not declared again on top)."""
    match member:
        case ast.AnnAssign(target=ast.Name(id=name)) | ast.Assign(targets=[ast.Name(id=name)]):
            return name
        case ast.FunctionDef(name=name) | ast.AsyncFunctionDef(name=name) | ast.ClassDef(name=name):
            return name
        case _:
            return None


def _with_defaults(statements: list[ast.stmt]) -> list[ast.stmt]:
    """To combine, in a class body, an annotation statement and the default-value assignment right after it into one statement. At runtime both dataclass and a plain class read the two statements as
    a field with a default, but copying them as two statements into the .pyi made pyright build the dataclass constructor from the annotation statement's value, read it as a field with no default,
    and calls that omit the field turned red (#2974 — agora's 17th ClickHouseDatabase, RunProcess regressed at L1377, etc.)."""
    given = [_given_default(statement, following) for statement, following in zip(statements, [*statements[1:], None])]
    absorbed = {index + 1 for index, merged in enumerate(given) if merged is not None}
    return [merged or statement for index, (statement, merged) in enumerate(zip(statements, given)) if index not in absorbed]


@dataclass(frozen=True)
class _Placed:
    """One field set on self inside __init__ — the name and the readable type (None if unreadable)."""

    name: str
    kind: ast.expr | None


def _argument_type(init: ast.FunctionDef, name: str) -> ast.expr | None:
    """Annotation of the __init__ parameter `name` (None if it is not a parameter or has no annotation) — to read the field type when a parameter is placed directly as a field."""
    listed = [*init.args.posonlyargs, *init.args.args, *init.args.kwonlyargs]
    found = next((a.annotation for a in listed if a.arg == name and a.annotation is not None), None)
    return None if found is None else _annotation(found) or found


def _placed(statement: ast.AST, init: ast.FunctionDef) -> _Placed | None:
    """Field set on self by one statement inside __init__ (None for a statement that sets no self field). An annotated assignment reads the annotation as the type; a plain
    assignment of a parameter reads that parameter's annotation as the type."""
    match statement:
        case ast.AnnAssign(target=ast.Attribute(value=ast.Name(id="self"), attr=attr), annotation=annotation):
            return _Placed(attr, _annotation(annotation) or annotation)
        case ast.Assign(targets=[ast.Attribute(value=ast.Name(id="self"), attr=attr)], value=ast.Name(id=name)):
            return _Placed(attr, _argument_type(init, name))
        case ast.Assign(targets=[ast.Attribute(value=ast.Name(id="self"), attr=attr)]):
            return _Placed(attr, None)
        case _:
            return None


def _init_attributes(node: ast.ClassDef, declared: frozenset[str]) -> list[ast.stmt]:
    """Declaration of fields set on self inside __init__. The type checker cannot read fields not written in the .pyi, so a class declaring only methods did not satisfy a Protocol that
    requires fields (WalStore and ByteLog). The type is the T of an annotated assignment (`(setv #^ T self.x …)`), or, when a parameter is placed directly, that parameter's annotation.
    A field with neither gets no inferred type and is Incomplete (reported as a place where the author should add an annotation). Names already declared in the class body, and private fields
    starting with `_` (not part of the type surface users read — emitting them would only add reports of fields with unknown types) are not added."""
    init = next((s for s in node.body if isinstance(s, ast.FunctionDef) and s.name == "__init__"), None)
    if init is None:
        return []
    placed = [found for statement in ast.walk(init) if (found := _placed(statement, init)) is not None]
    names = dict.fromkeys(p.name for p in placed if not p.name.startswith("_") and p.name not in declared)
    return [
        ast.AnnAssign(
            target=_name(name),
            annotation=next((p.kind for p in placed if p.name == name and p.kind is not None), _name(_INCOMPLETE)),
            value=None,
            simple=1,
        )
        for name in names
    ]


def _class(node: ast.ClassDef, type_vars: frozenset[str] = frozenset()) -> ast.ClassDef:
    """Declaration of one class (keeps decorators, bases, fields, and method shapes, and drops body expressions). type_vars = names of module type parameters (to read answer types).
    The class's own type parameters (defeffect's :tp — `class E[T](…)` in the type-check expansion) are also carried into the declaration, and the answer type reads the class's own type parameters as types too (#2939)."""
    members = [member for statement in _with_defaults(node.body) if (member := _member(statement)) is not None]
    declared = frozenset(name for member in members if (name := _member_name(member)) is not None)
    body = [*_init_attributes(node, declared), *members]
    readable = type_vars | {parameter.name for parameter in _type_params(node)}
    answer = next(
        (found for statement in node.body if (found := _declared_answer(statement, readable)) is not None), None
    )
    return ast.ClassDef(
        name=node.name,
        bases=[_effect_base(base, answer) for base in node.bases],
        keywords=node.keywords,
        body=body or [ast.Expr(value=ast.Constant(value=...))],
        decorator_list=[d for d in node.decorator_list if not _reads_hidden(d)],
        type_params=_type_params(node),
    )


def _constant(name: str, value: ast.expr, scan: _Scan) -> ast.stmt:
    """Declaration of one module constant (type aliases and TypeVar are kept as written; others get an annotation of the value's type)."""
    match value:
        case ast.BinOp(op=ast.BitOr()) | ast.Subscript() if _type_like(value):
            return ast.AnnAssign(target=_name(name), annotation=_name("TypeAlias"), value=value, simple=1)
        case ast.Name(id=other) if _camel(other):
            return ast.Assign(targets=[_name(name)], value=value)
        case ast.Call(func=ast.Name(id=maker) | ast.Attribute(attr=maker)) if maker in _TYPE_MAKERS:
            return ast.Assign(targets=[_name(name)], value=value)
        case _:
            kind = _value_type(value, scan) or _name(_INCOMPLETE)
            return ast.AnnAssign(target=_name(name), annotation=kind, value=None, simple=1)


def _macro_helper(module: str | None, name: str) -> bool:
    """Whether this is a doeff_hy.macros helper imported by a macro expansion (_install_guard_globals, _guard_performed, etc. — not part of the type surface, so
    not re-exported. Re-exporting would make the .pyi depend on the macro module, which hit the quality check's dependency contract — #2842)."""
    return module == "doeff_hy.macros" and name.startswith("_")


def _reexports(statement: ast.Import | ast.ImportFrom) -> tuple[ast.stmt, ...]:
    """Split one import statement into statements that re-export the names (`X as X`) (macro helpers and `hy` are dropped)."""
    match statement:
        case ast.ImportFrom(module=str(module)) if module == "__future__" or module.startswith("doeff_hy._static_types"):
            return ()
        case ast.ImportFrom(module=module, names=names, level=level):
            return tuple(
                ast.ImportFrom(module=module, names=[ast.alias(name=a.name, asname=a.asname or a.name)], level=level)
                for a in names
                if a.name != "*" and not hidden_name(a.asname or a.name) and not _macro_helper(module, a.name)
            )
        case ast.Import(names=names):
            return tuple(
                ast.Import(names=[ast.alias(name=a.name, asname=a.asname or (a.name if "." not in a.name else None))])
                for a in names
                if a.name.split(".")[0] != "hy" and not hidden_name(a.asname or a.name)
            )


def _step(state: _Scan, statement: ast.stmt) -> _Scan:
    """Read one module-level statement and return the next state with declarations, re-exported imports, and constant types added
    (statements with no type surface — expressions, if, try, etc. — are discarded)."""
    match statement:
        case ast.Import() | ast.ImportFrom():
            return replace(state, imports=(*state.imports, *_reexports(statement)))
        case ast.FunctionDef() | ast.AsyncFunctionDef():
            return state.defined(statement.name, _function(statement, method=False), public=not hidden_name(statement.name))
        case ast.ClassDef() if not hidden_name(statement.name):
            return state.declared(statement.name, _class(statement, state.type_vars()))
        case ast.AnnAssign(target=ast.Name(id=name), annotation=annotation, value=value) if not hidden_name(name):
            kind = _annotation(annotation) or annotation
            alias = isinstance(kind, ast.Name) and kind.id == "TypeAlias"
            node = ast.AnnAssign(target=_name(name), annotation=kind, value=value if alias else None, simple=1)
            return state.declared(name, node)
        case ast.Assign(targets=[ast.Name(id=name)], value=value) if not hidden_name(name):
            return state.declared(name, _constant(name, value, state))
        case ast.Expr(
            value=ast.Call(
                func=ast.Name(id="setattr"),
                args=[ast.Name(id=name), ast.Constant(value="__doeff_effects__"), ast.Tuple(elts=[])],
            )
        ):
            return state.effect_free(name)
        case _:
            return state


def _incomplete(node: ast.expr | None) -> bool:
    """Whether a type expression contains Incomplete (the marker for places where no type could be produced)."""
    return node is not None and any(isinstance(n, ast.Name) and n.id == _INCOMPLETE for n in ast.walk(node))


def _gaps(statement: ast.stmt, owner: str) -> tuple[str, ...]:
    """Names of places within one declaration where no type could be produced and Incomplete was used (reported as places where the author should add contracts)."""
    match statement:
        case ast.AnnAssign(target=ast.Name(id=name), annotation=annotation) if _incomplete(annotation):
            return (f"{owner}{name}",)
        case ast.FunctionDef(name=name, args=arguments, returns=returns):
            listed = [*arguments.posonlyargs, *arguments.args, *arguments.kwonlyargs]
            rest = [a for a in (arguments.vararg, arguments.kwarg) if a is not None]
            missing = tuple(f"{owner}{name} parameter {a.arg}" for a in (*listed, *rest) if _incomplete(a.annotation))
            return (*missing, *((f"{owner}{name} answer",) if _incomplete(returns) else ()))
        case ast.ClassDef(name=name, body=body):
            return tuple(gap for member in body for gap in _gaps(member, f"{owner}{name}."))
        case _:
            return ()


def _bound(statement: ast.stmt) -> tuple[str, ...]:
    """Names bound by one import statement (so helper type imports are not placed twice)."""
    match statement:
        case ast.Import(names=names) | ast.ImportFrom(names=names):
            return tuple(a.asname or a.name for a in names)
        case _:
            return ()


def _unread_module_import(line: ast.stmt, reads: set[str]) -> bool:
    """Whether a module import (`import a.b`, `import os as os`) is one whose bound name no declaration reads — so it is not copied. Users do not look up a module as
    `from m import os`, so re-exporting has no point and only added dependencies to the .pyi: the `doeff_hy.record` pulled in by the defrecord expansion hit
    the quality check's module dependency contract (#2886), and `import os` hit "dependency from the pure layer to the IO API" (#2925).
    Keep it if a declaration reads `a.b.X` or `os.PathLike`. Imports that pull names (`from m import X as X`) are re-exported, so they are not dropped."""
    match line:
        case ast.Import(names=[ast.alias(name=name, asname=asname)]):
            return (asname or name.split(".")[0]) not in reads
        case _:
            return False


def _render(state: _Scan, source_name: str) -> StubText:
    """Assemble the .pyi body from the final state (helper type imports only for those a declaration reads; the same import only once)."""
    declared = state.declarations
    body = [d.node for index, d in enumerate(declared) if d.name not in {e.name for e in declared[index + 1 :]}]
    keys = [ast.unparse(line) for line in state.imports]
    reads = {n.id for statement in body for n in ast.walk(statement) if isinstance(n, ast.Name)}
    imports = [
        line
        for index, line in enumerate(state.imports)
        if keys[index] not in keys[:index] and not _unread_module_import(line, reads)
    ]
    bound = {name for line in imports for name in _bound(line)}
    head = [
        ast.ImportFrom(module=helper.module, names=[ast.alias(name=helper.name, asname=helper.asname)], level=0)
        for helper in _HELPERS
        if helper.reads in reads and (helper.asname or helper.name) not in bound
    ]
    module = ast.fix_missing_locations(ast.Module(body=[*head, *imports, *body], type_ignores=[]))
    first = f"{MARK} (source = {source_name}; regenerate with python -m doeff_hy._static_stub --write <the .hy next to this .pyi>)"
    gaps = tuple(gap for statement in body for gap in _gaps(statement, ""))
    return StubText(f"{first}\n\n{ast.unparse(module)}\n", gaps)


def stub_from(projection: Projection) -> StubText:
    """Build the .pyi body from the type-checking expansion of one .hy."""
    empty = _Scan(imports=(), declarations=())
    return _render(reduce(_step, ast.parse(projection.text).body, empty), projection.source.name)


def stub_of(root: Path, roots: list[Path], source: Path) -> StubText:
    """Build the .pyi body from one .hy (so that users' strict type checking does not read Hy module names as Unknown)."""
    projected = project(root, roots, source)
    if isinstance(projected, CompileFailure):
        raise StubUnmade(projected.diagnostic.render())
    return stub_from(projected)


def generated(stub: Path) -> bool:
    """Whether this is a .pyi generated by the tool (line 1 starts with MARK_HEAD — to tell it from a hand-written .pyi, which --write and build_stubs leave alone)."""
    return stub.is_file() and stub.read_text(encoding="utf-8").startswith(MARK_HEAD)


@dataclass(frozen=True)
class Built:
    """What one build_stubs did: .pyi written (new or changed), left as they were (same text), hand-written ones left alone, and tool .pyi removed
    because their .hy is gone (an ignored .pyi is not removed by git, and a type checker would keep reading the names of a deleted module)."""

    written: tuple[Path, ...]
    kept: tuple[Path, ...]
    hand_written: tuple[Path, ...]
    removed: tuple[Path, ...]


def _write_atomically(path: Path, text: str) -> None:
    """Write through a temporary name in the same dir and rename — two users building the same shared checkout at once (an editable install writes
    into the checkout's src) never leave a half-written .pyi for the other's type checker; the last rename wins with a whole file."""
    handle, temporary = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as stream:
            stream.write(text)
        # mkstemp makes the file readable by its owner only; a declaration is read by every user of the checkout and copied into wheels.
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def build_stubs(root: Path, directories: list[Path], cache_dir: Path | None = None) -> Built:
    """Make the .pyi of every .hy under directories (root = the import root that gives the module names, e.g. packages/<name>/src).

    Expansions come from the expansion cache when their record still holds (cache_dir; default = the check's store, default_cache_dir), and the
    ones not found are expanded in parallel — a fresh doeff-cluster took 92 seconds file by file. A .hy that does not expand stops the build
    (StubUnmade): a package whose module cannot be read must not install with a missing or stale declaration."""
    root = _absolute(root)
    roots = import_roots(root, pyright_settings(root))
    sys.path.extend(str(entry) for entry in roots if str(entry) not in sys.path)
    sources = hy_files([_absolute(d) for d in directories])
    closure = project_closure(root, roots, sources, cache_dir or default_cache_dir(), expander_limit(None))
    failed = [f for f in closure.failures if f.source in set(sources)]
    if failed:
        raise StubUnmade("\n".join(f.diagnostic.render() for f in failed))
    written: list[Path] = []
    kept: list[Path] = []
    hand_written: list[Path] = []
    for source in sources:
        stub = source.with_suffix(".pyi")
        if stub.exists() and not generated(stub):
            hand_written.append(stub)
            continue
        text = stub_from(closure.projections[source]).text
        if stub.exists() and stub.read_text(encoding="utf-8") == text:
            kept.append(stub)
        else:
            _write_atomically(stub, text)
            written.append(stub)
    removed = [
        stub
        for directory in directories
        for stub in sorted(_absolute(directory).rglob("*.pyi"))
        if generated(stub) and not stub.with_suffix(".hy").exists()
    ]
    for stub in removed:
        stub.unlink()
    return Built(tuple(written), tuple(kept), tuple(hand_written), tuple(removed))


#: Red message text for "type unknown" (names that are entirely unknown, unresolvable imports. Names with partially unknown types — partially unknown — are a separate matter of refining contracts).
_UNKNOWN = re.compile(r"is unknown|could not be resolved|unknown import symbol")


@dataclass(frozen=True)
class UsedModule:
    """One module that users import (a name under the package; if empty, the package entry point) and its sequence of names (in Hy spelling) — material for building the users' name probe."""

    module: str
    names: tuple[str, ...]


def users_probe(package: str, used: tuple[UsedModule, ...]) -> str:
    """Module of the check that binds each user-facing name to a separate name (so that if the bound name's type is Unknown, a strict red appears on that line)."""
    imports = [f"(import {'.'.join(filter(None, (package, u.module)))} [{' '.join(u.names)}])" for u in used]
    names = [name for u in used for name in u.names]
    bindings = [f"(setv used-{index} {name})" for index, name in enumerate(names)]
    return "\n".join([*imports, "", *bindings, ""])


def strict_errors(workdir: Path, probe_text: str) -> tuple[str, ...]:
    """Check the check module (Hy source) under the same strict as users' type gate and return the reds as "line: rule: message" — so each package's check can verify that the .pyi types
    reach the way users write (that a mix-up turns red)."""
    probe = workdir / "probe.hy"
    probe.write_text(probe_text, encoding="utf-8")
    command = [sys.executable, "-m", "doeff_hy._static_check", "--root", str(workdir), "--json", "--strict", "--no-cache", str(probe)]
    done = subprocess.run(command, capture_output=True, text=True, timeout=240, check=False)
    diagnostics: list[dict[str, object]] = json.loads(done.stdout) if done.stdout.strip() else []
    return tuple(f"{d['line']}: {d['rule']}: {d['message']}" for d in diagnostics if d["severity"] == "error")


def unknown_in_users(workdir: Path, package: str, used: tuple[UsedModule, ...]) -> tuple[str, ...]:
    """Check the check module that binds the users' names under strict and return the "type unknown" and Hy compile reds
    (so each package's check can verify in one line that the .pyi reaches users — if empty, users can read every name with types)."""
    errors = strict_errors(workdir, users_probe(package, used))
    return tuple(e for e in errors if "hy-compile" in e or _UNKNOWN.search(e))


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: write .pyi (--write), build every .pyi of package dirs (--build), print to stdout (default)."""
    parser = argparse.ArgumentParser(
        prog="doeff-hy-stub", description="Build the type declarations (.pyi) of a Hy module from the expansion used for type checking"
    )
    parser.add_argument("paths", nargs="+", type=Path)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--write", action="store_true", help="write the .pyi next to the .hy")
    action.add_argument(
        "--build", action="store_true", help="make the .pyi of every .hy under the given dirs, expanding only what the expansion cache lacks"
    )
    parser.add_argument("--replace", action="store_true", help="with --write, also replace hand-written .pyi files")
    args = parser.parse_args(argv)
    root = _absolute(args.root)
    if args.build:
        try:
            built = build_stubs(root, [p if p.is_absolute() else Path.cwd() / p for p in args.paths])
        except StubUnmade as error:
            print(f"doeff-hy-stub: could not generate: {error}", file=sys.stderr)
            return 2
        print(
            f"doeff-hy-stub: {len(built.written)} written, {len(built.kept)} unchanged, {len(built.hand_written)} hand-written left alone, "
            f"{len(built.removed)} removed (no .hy)",
            file=sys.stderr,
        )
        return 0
    roots = import_roots(root, pyright_settings(root))
    # Roots are appended at the back (so the macro modules pulled by the expansion's require can be read). Prepending would make the source tree
    # (packages/doeff-vm) without a built extension hide the built one installed in the environment.
    sys.path.extend(str(entry) for entry in roots if str(entry) not in sys.path)
    sources = hy_files([p if p.is_absolute() else Path.cwd() / p for p in args.paths])
    for source in sources:
        stub = source.with_suffix(".pyi")
        try:
            made = stub_of(root, roots, source)
        except StubUnmade as error:
            print(f"doeff-hy-stub: could not generate: {error}", file=sys.stderr)
            return 2
        if made.incomplete:
            print(f"{source.relative_to(root)}: Incomplete — {', '.join(made.incomplete)}", file=sys.stderr)
        if not args.write:
            sys.stdout.write(made.text)
        elif stub.exists() and not generated(stub) and not args.replace:
            print(f"{stub.relative_to(root)}: not written because it is a hand-written .pyi (use --replace to overwrite)", file=sys.stderr)
        else:
            stub.write_text(made.text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
